"""Build self-hosted webfonts from the supplied Alibaba PuHuiTi 3 package.

Requires fonttools[woff]. Run from any directory with the font package as an
argument. All original Unicode characters are retained across disjoint subsets.
The generated CSS lets browsers request only the characters and weights in use.
"""

import argparse
import io
import json
from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

WEB = Path(__file__).resolve().parents[1]
REPO = WEB.parents[1]
WEIGHTS = [("55-Regular", "regular", 400), ("65-Medium", "medium", 500),
           ("75-SemiBold", "semibold", 600), ("85-Bold", "bold", 700)]


def unicode_ranges(codepoints):
    points = sorted(codepoints)
    start = end = points[0]
    ranges = []
    for point in points[1:]:
        if point == end + 1:
            end = point
        else:
            ranges.append((start, end))
            start = end = point
    ranges.append((start, end))
    return ",".join(f"U+{start:X}" if start == end else f"U+{start:X}-{end:X}"
                    for start, end in ranges)


def site_characters():
    text = []
    for directory in [WEB / "app", WEB / "components", WEB / "lib"]:
        for file in sorted(directory.rglob("*")):
            if file.is_file() and file.suffix in {".ts", ".tsx", ".css"} and file.name != "fonts.css":
                text.append(file.read_text(encoding="utf-8"))
    for file in sorted((REPO / "packages/contracts").glob("*.json")):
        text.append(json.dumps(json.loads(file.read_text(encoding="utf-8")), ensure_ascii=False))
    return {ord(character) for character in "".join(text)}


def build(source_root):
    output = WEB / "public/fonts/alibaba-puhuiti-3"
    output.mkdir(parents=True, exist_ok=True)
    corpus = site_characters()
    css = ["/* Generated by apps/web/scripts/build-fonts.py. Do not edit by hand. */"]
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.layout_features = ["*"]
    total_size = 0
    for suffix, label, weight in WEIGHTS:
        source = source_root / f"AlibabaPuHuiTi-3-{suffix}" / f"AlibabaPuHuiTi-3-{suffix}.ttf"
        data = source.read_bytes()
        with TTFont(io.BytesIO(data), recalcTimestamp=False) as original:
            supported = set(original.getBestCmap())
            assert original["OS/2"].usWeightClass == weight
        latin = {point for point in supported if point <= 0x24F or 0x2000 <= point <= 0x206F}
        common = (supported & corpus) - latin
        remaining = sorted(supported - latin - common)
        groups = [("latin", latin), ("common", common)]
        groups.extend((f"{index // 2048 + 1:02d}", set(remaining[index:index + 2048]))
                      for index in range(0, len(remaining), 2048))
        seen = set()
        weight_size = 0
        for group, points in groups:
            if not points:
                continue
            assert not (seen & points)
            seen.update(points)
            with TTFont(io.BytesIO(data), recalcTimestamp=False) as font:
                subsetter = subset.Subsetter(options=options)
                subsetter.populate(unicodes=points)
                subsetter.subset(font)
                assert set(font.getBestCmap()) == points
                font.flavor = "woff2"
                filename = f"{label}-{group}.woff2"
                target = output / filename
                font.save(target)
                weight_size += target.stat().st_size
            css.append(
                '@font-face{font-family:"Alibaba PuHuiTi 3";'
                f'src:url("/fonts/alibaba-puhuiti-3/{filename}") format("woff2");'
                f'font-style:normal;font-weight:{weight};font-display:swap;'
                f'unicode-range:{unicode_ranges(points)}' + "}"
            )
        assert seen == supported, "A character was lost while subsetting."
        total_size += weight_size
        print(f"{label}: {len(supported)} characters, {len(groups)} subsets, {weight_size:,} bytes", flush=True)
    (WEB / "app/fonts.css").write_text("\n".join(css) + "\n", encoding="utf-8")
    print(f"Generated {len(css) - 1} font faces; total {total_size:,} bytes.", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", type=Path, help="Path to the supplied AlibabaPuHuiTi-3 directory")
    build(parser.parse_args().source.resolve())
